-- सार्वजनिक साइट: सभी लोग रिकॉर्ड पढ़ और जोड़ सकते हैं। बिना लॉगिन insert/upload में spam का जोखिम है।
-- public anon key ही वेबसाइट में रखें; service_role key कभी भी frontend में न डालें.

create table if not exists public.chanda_records (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  mobile text,
  address text,
  amount numeric(12,2) not null check (amount > 0),
  remarks text,
  image_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.material_records (
  id bigint generated by default as identity primary key,
  material_name text not null check (char_length(material_name) between 1 and 150),
  description text,
  details_description text,
  image_url text,
  advance_paid numeric(12,2) not null default 0 check (advance_paid >= 0),
  total_amount numeric(12,2) not null check (total_amount >= 0),
  created_at timestamptz not null default now(),
  constraint advance_not_more_than_total check (advance_paid <= total_amount)
);

alter table public.chanda_records enable row level security;
alter table public.material_records enable row level security;

drop policy if exists "Public can view chanda records" on public.chanda_records;
create policy "Public can view chanda records" on public.chanda_records for select to anon, authenticated using (true);
drop policy if exists "Public can add chanda records" on public.chanda_records;
create policy "Public can add chanda records" on public.chanda_records for insert to anon, authenticated with check (true);

drop policy if exists "Public can view material records" on public.material_records;
create policy "Public can view material records" on public.material_records for select to anon, authenticated using (true);
drop policy if exists "Public can add material records" on public.material_records;
create policy "Public can add material records" on public.material_records for insert to anon, authenticated with check (true);

-- Storage bucket for public image viewing and anonymous uploads (images max 5 MB in frontend validation).
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('donor-images', 'donor-images', true, 5242880, array['image/jpeg','image/png','image/webp','image/gif','image/avif'])
on conflict (id) do update set public = true, file_size_limit = 5242880,
  allowed_mime_types = array['image/jpeg','image/png','image/webp','image/gif','image/avif'];

drop policy if exists "Public can view donor images" on storage.objects;
create policy "Public can view donor images" on storage.objects for select to anon, authenticated using (bucket_id = 'donor-images');
drop policy if exists "Public can upload donor images" on storage.objects;
create policy "Public can upload donor images" on storage.objects for insert to anon, authenticated with check (bucket_id = 'donor-images');

